// Command gen writes ../fields.go from the WP Engine API's OpenAPI document:
// the fields each operation's request body may have, and the fields each
// schema has, as dotted paths (account.id). The client's tests and the fake
// server check against them, so a field the API doesn't have fails a test.
//
//	go generate ./internal/openapi
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
)

const source = "https://api.wpengineapi.com/v1/swagger"

type schema struct {
	Ref        string             `json:"$ref"`
	Type       string             `json:"type"`
	Properties map[string]*schema `json:"properties"`
	Items      *schema            `json:"items"`
	AllOf      []*schema          `json:"allOf"`
	OneOf      []*schema          `json:"oneOf"`
	AnyOf      []*schema          `json:"anyOf"`
}

type document struct {
	Info struct {
		Version string `json:"version"`
	} `json:"info"`
	Paths map[string]map[string]struct {
		OperationID string `json:"operationId"`
		RequestBody *struct {
			Ref     string `json:"$ref"`
			Content map[string]struct {
				Schema *schema `json:"schema"`
			} `json:"content"`
		} `json:"requestBody"`
	} `json:"paths"`
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

func main() {
	response, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer response.Body.Close()
	raw, err := io.ReadAll(response.Body)
	if err != nil {
		log.Fatal(err)
	}
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}

	requests := map[string][]string{}
	for _, operations := range doc.Paths {
		for _, operation := range operations {
			if operation.OperationID == "" || operation.RequestBody == nil {
				continue
			}
			if content, ok := operation.RequestBody.Content["application/json"]; ok && content.Schema != nil {
				requests[operation.OperationID] = fields(&doc, content.Schema, "", map[string]bool{})
			}
		}
	}
	schemas := map[string][]string{}
	for name, s := range doc.Components.Schemas {
		schemas[name] = fields(&doc, s, "", map[string]bool{})
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen from %s (version %s). DO NOT EDIT.\n\n", source, doc.Info.Version)
	fmt.Fprintf(&out, "package openapi\n\n// Version is the API document's version.\nconst Version = %q\n\n", doc.Info.Version)
	write(&out, "Requests are the fields each operation's JSON request body may have.", "Requests", requests)
	write(&out, "Schemas are the fields of each schema.", "Schemas", schemas)
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("fields.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// fields lists a schema's properties as dotted paths, through references,
// compositions and arrays.
func fields(doc *document, s *schema, prefix string, seen map[string]bool) []string {
	if s == nil {
		return nil
	}
	if s.Ref != "" {
		name := strings.TrimPrefix(s.Ref, "#/components/schemas/")
		if seen[name] {
			return nil
		}
		next := map[string]bool{name: true}
		for k := range seen {
			next[k] = true
		}
		return fields(doc, doc.Components.Schemas[name], prefix, next)
	}
	var out []string
	for _, group := range [][]*schema{s.AllOf, s.OneOf, s.AnyOf} {
		for _, part := range group {
			out = append(out, fields(doc, part, prefix, seen)...)
		}
	}
	if s.Items != nil {
		out = append(out, fields(doc, s.Items, prefix, seen)...)
	}
	for name, property := range s.Properties {
		path := prefix + name
		out = append(out, path)
		out = append(out, fields(doc, property, path+".", seen)...)
	}
	sort.Strings(out)
	unique := out[:0]
	for i, field := range out {
		if i == 0 || field != out[i-1] {
			unique = append(unique, field)
		}
	}
	return unique
}

func write(out *bytes.Buffer, comment, name string, values map[string][]string) {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	fmt.Fprintf(out, "// %s\nvar %s = map[string][]string{\n", comment, name)
	for _, key := range keys {
		fmt.Fprintf(out, "%q: {", key)
		for _, field := range values[key] {
			fmt.Fprintf(out, "%q,", field)
		}
		fmt.Fprintf(out, "},\n")
	}
	fmt.Fprintf(out, "}\n\n")
}
